public class Numeros {
    public static void main(String[] args) {
        int a = 7, b = 2;
        System.out.println(a / b);
        System.out.println(a % b);
        System.out.println(-7 / 2);
        System.out.println(-7 % 2);
        System.out.println((double) a / b);
        System.out.println(a / (double) b);
        System.out.println((double) (a / b));
        System.out.println(0.1 + 0.2);
        System.out.println(1.0 / 3);
        System.out.println(100.0);
        System.out.println(1e7);
        System.out.println(12345678.9);
        System.out.println(0.001);
        System.out.println(0.0001);
        System.out.println(1.5e-5);
        System.out.println(1.0f / 3);
        System.out.println(3.14f);
        System.out.println(1.1f + 2.2f);
        System.out.println(10 / 3.0f);
        System.out.println(Integer.MAX_VALUE + 1);
        System.out.println(Integer.MIN_VALUE - 1);
        System.out.println(1000000 * 1000000);
        System.out.println(1000000L * 1000000L);
        long f = 1;
        for (int i = 1; i <= 20; i++) f *= i;
        System.out.println(f);
        System.out.println(Long.MAX_VALUE);
        System.out.println(Long.MAX_VALUE + 1);
        char c = 'A';
        System.out.println(c);
        System.out.println(c + 1);
        System.out.println((char) (c + 1));
        c++;
        System.out.println(c);
        c += 2;
        System.out.println(c);
        System.out.println('a' + 'b');
        System.out.println("" + 'a' + 'b');
        System.out.println('a' + 'b' + "c");
        System.out.println("x" + 1 + 2);
        System.out.println(1 + 2 + "x");
        System.out.println("x" + (1 + 2));
        System.out.println((int) 3.99);
        System.out.println((int) -3.99);
        System.out.println((int) 'A');
        System.out.println((byte) 200);
        System.out.println((short) 70000);
        System.out.println((int) 1e20);
        System.out.println((long) 1e20);
        System.out.println(Math.round(2.5));
        System.out.println(Math.round(-2.5));
        System.out.println(Math.round(3.49));
        System.out.println(Math.floor(-1.1));
        System.out.println(Math.ceil(1.1));
        System.out.println(Math.pow(2, 10));
        System.out.println(Math.sqrt(2));
        System.out.println(Math.abs(-5));
        System.out.println(Math.abs(-5.5));
        System.out.println(Math.max(3, 7));
        System.out.println(Math.max(3, 7.5));
        System.out.println(Math.min(2L, 9));
        int x = 5;
        x += 2.7;
        System.out.println(x);
        x /= 2;
        System.out.println(x);
        x *= 1.5;
        System.out.println(x);
        int y = 10;
        int z = y++ + ++y;
        System.out.println(y + " " + z);
        int w = 3;
        w = w++ * 2;
        System.out.println(w);
        boolean p = true, q = false;
        System.out.println(p && q);
        System.out.println(p || q);
        System.out.println(!p);
        System.out.println(p ^ q);
        System.out.println(5 & 3);
        System.out.println(5 | 3);
        System.out.println(5 ^ 3);
        System.out.println(1 << 4);
        System.out.println(-16 >> 2);
        System.out.println(-16 >>> 28);
        System.out.println(5 > 3 ? "si" : "no");
        System.out.println(true ? 1 : 2.0);
        System.out.println(1.0 / 0);
        System.out.println(-1.0 / 0);
        System.out.println(0.0 / 0);
        System.out.println(5.5 % 2);
        System.out.printf("%.2f%n", 3.14159);
        System.out.printf("%5d|%-5d|%05d%n", 42, 42, 42);
        System.out.printf("%s tiene %d años%n", "Ana", 25);
        System.out.printf("%10s|%-10s|%n", "hola", "hola");
        System.out.printf("%.1f %.0f %.3f%n", 2.25, 2.5, 1.0005);
        System.out.printf("%c %b %x %%%n", 'z', true, 255);
        System.out.printf("%,d%n", 1234567);
        System.out.println(String.format("%08.3f", 3.14159));
        System.out.println(Integer.parseInt("42") + 1);
        System.out.println(Double.parseDouble("3.5") * 2);
        System.out.println(Integer.toString(5) + 5);
        System.out.println(String.valueOf(5) + 5);
        System.out.println(Integer.valueOf(7));
        System.out.println(Integer.toBinaryString(10));
        System.out.println(Integer.toHexString(255));
        System.out.println(Character.isDigit('5'));
        System.out.println(Character.toUpperCase('b'));
        System.out.println(Character.getNumericValue('7'));
    }
}
